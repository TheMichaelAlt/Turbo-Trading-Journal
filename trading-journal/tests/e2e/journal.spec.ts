import { test, expect, type Page } from '@playwright/test'
const nav = (page: Page, name: string) => page.getByRole('navigation', { name: 'Main navigation' }).getByRole('button', { name: new RegExp(`^${name}( \\d+)?$`) }).click()
const saved = (page: Page) => expect(page.locator('.save-status')).toHaveText('Saved locally')
async function essentials(page: Page) {
  await page.locator('#field-date').fill('2026-09-01')
  await page.locator('#field-timeIn').fill('09:30')
  await page.locator('#field-timeOut').fill('10:00')
  await page.locator('#field-direction').selectOption('LONG')
  await page.locator('#field-contract').fill('ES')
  await page.locator('#field-size').fill('1')
  await page.locator('#field-pnl').fill('0')
  await page.locator('#field-account').fill('Sim')
  await page.locator('#field-strategy').fill('Breakout')
}
test.beforeEach(async ({ page }) => { await page.goto('/'); await expect(page.getByRole('heading', { name: 'Performance overview.' })).toBeVisible() })
test('unfinished → completed → edited → deleted, including zero PnL', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message))
  await nav(page, 'Trade log')
  await page.locator('#field-contract').fill('ES')
  await page.locator('#field-pnl').fill('0')
  await page.getByRole('button', { name: 'Save unfinished trade' }).click()
  await expect(page.locator('.draft-card')).toHaveCount(1)
  await nav(page, 'Master trade log'); await expect(page.getByRole('heading', { name: 'A clean slate.' })).toBeVisible()
  await nav(page, 'Trade log'); await page.getByRole('button', { name: 'Finish entry' }).click()
  await expect(page.locator('#field-pnl')).toHaveValue('0')
  await essentials(page)
  await page.locator('#field-notes').fill('A disciplined breakeven.')
  await page.getByRole('button', { name: 'Save completed trade' }).click()
  await expect(page.locator('.draft-card')).toHaveCount(0)
  await nav(page, 'Master trade log'); await expect(page.locator('tbody tr')).toHaveCount(1)
  await page.getByRole('button', { name: 'Edit trade ES 2026-09-01' }).click()
  await expect(page.locator('#field-notes')).toHaveValue('A disciplined breakeven.')
  await page.locator('#field-pnl').fill('125.50')
  await page.getByRole('button', { name: 'Save completed trade' }).click(); await saved(page)
  await page.reload(); await nav(page, 'Master trade log'); await expect(page.locator('tbody')).toContainText('$125.50')
  await page.getByRole('button', { name: 'Delete trade ES 2026-09-01' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Delete trade', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'A clean slate.' })).toBeVisible()
  expect(errors).toEqual([])
})
