test('backup restore validates files and restores exported records', async ({ page }) => {
  await page.getByRole('button', { name: 'Explore sample data' }).click(); await saved(page); await nav(page, 'Settings')
  const download = page.waitForEvent('download'); await page.getByRole('button', { name: 'Export backup', exact: true }).click()
  const path = await (await download).path()
  await page.getByRole('button', { name: 'Remove sample trades', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Remove samples', exact: true }).click()
  await page.getByLabel('Import backup file', { exact: true }).setInputFiles({ name: 'invalid.json', mimeType: 'application/json', buffer: Buffer.from('{"version":1}') })
  await expect(page.getByRole('alert')).toContainText('Unsupported or incomplete backup')
  await page.getByLabel('Import backup file', { exact: true }).setInputFiles(path!)
  await expect(page.getByRole('dialog')).toContainText('64 trades')
  await page.getByRole('button', { name: 'Back up current data & restore', exact: true }).click(); await saved(page)
  await nav(page, 'Dashboard'); await expect(page.locator('.stat-card').first()).toContainText('64 completed trades')
})
test('failed saves show an error and resubmitting never duplicates a trade', async ({ page }) => {
  await nav(page, 'Trade log'); await essentials(page)
  await page.evaluate(() => {
    const original = IDBObjectStore.prototype.put
    IDBObjectStore.prototype.put = function (...args) {
      IDBObjectStore.prototype.put = original
      throw new Error(`Simulated storage failure for ${args.length} argument(s)`)
    }
  })
  await page.getByRole('button', { name: 'Save completed trade' }).click()
  await expect(page.getByRole('alert')).toContainText('haven’t been saved')
  await expect(page.locator('#field-pnl')).toHaveValue('0')
  await page.getByRole('button', { name: 'Save completed trade' }).click(); await saved(page)
  await nav(page, 'Master trade log'); await expect(page.locator('tbody tr')).toHaveCount(1)
  await page.reload(); await nav(page, 'Master trade log'); await expect(page.locator('tbody tr')).toHaveCount(1)
})
